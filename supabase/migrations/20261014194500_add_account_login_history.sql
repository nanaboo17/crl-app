create table if not exists public.account_login_history (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  role text,
  organization text,
  provider text,
  ip_address text,
  user_agent text,
  logged_in_at timestamptz not null default now()
);

create index if not exists account_login_history_email_logged_in_at_idx
  on public.account_login_history (lower(email), logged_in_at desc);

create index if not exists account_login_history_logged_in_at_idx
  on public.account_login_history (logged_in_at desc);

alter table public.account_login_history enable row level security;

drop policy if exists account_login_history_insert_own on public.account_login_history;
create policy account_login_history_insert_own
on public.account_login_history
for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists account_login_history_superadmin_select on public.account_login_history;
create policy account_login_history_superadmin_select
on public.account_login_history
for select
to authenticated
using (public.current_role() = 'superadmin');

revoke update, delete on public.account_login_history from anon, authenticated;
grant select, insert on public.account_login_history to authenticated;
